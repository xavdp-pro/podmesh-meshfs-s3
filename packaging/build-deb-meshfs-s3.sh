#!/usr/bin/env bash
# =============================================================================
# PodMesh MeshFS S3 Gateway v2.3.0 — Debian 13 (Trixie) Package Builder
# Hardened under Claude Fable 5.1 & GPT-6 Astra Counter-Reviews:
#  - Enforces 0755 on ./ and OS directories; 0700 on /etc/meshfs & /var/lib/meshfs/s3
#  - Debian 13 usrmerge compliance (/usr/lib/systemd/system/meshfs-s3.service)
#  - Ships /usr/bin/meshfs-s3 (Pure Rust S3 Gateway + AI-First CLI)
#  - Protects /etc/meshfs/s3.json in DEBIAN/conffiles
#  - Zero-Touch CSPRNG generation of MESHFS_S3_ACCESS_KEY & MESHFS_S3_SECRET_KEY
#    into /etc/meshfs/s3.env (0600) in postinst
# =============================================================================
set -euo pipefail
umask 0022

PKG_NAME="podmesh-meshfs-s3"
PKG_VERSION="2.4.1"
PKG_ARCH="amd64"
ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
BUILD_DIR="$(mktemp -d /tmp/build-${PKG_NAME}.XXXXXX)"
DIST_DIR="${ROOT_DIR}/dist"
RUST_BIN="${ROOT_DIR}/target/release/meshfs-s3"

echo "=== [MeshFS-S3] Packaging Debian 13 (Trixie): ${PKG_NAME}_${PKG_VERSION}_${PKG_ARCH}.deb ==="

echo "Compiling release binary for MeshFS-S3 v${PKG_VERSION}..."
cargo build --release --manifest-path "${ROOT_DIR}/Cargo.toml"

trap 'rm -rf "${BUILD_DIR}"' EXIT

chmod 0755 "${BUILD_DIR}"
mkdir -p -m 0755 "${BUILD_DIR}/DEBIAN"
mkdir -p -m 0755 "${BUILD_DIR}/usr" "${BUILD_DIR}/usr/bin" "${BUILD_DIR}/usr/lib" \
  "${BUILD_DIR}/usr/lib/systemd" "${BUILD_DIR}/usr/lib/systemd/system"
mkdir -p -m 0755 "${BUILD_DIR}/etc" "${BUILD_DIR}/var" "${BUILD_DIR}/var/lib"
mkdir -p -m 0700 "${BUILD_DIR}/etc/meshfs"
mkdir -p -m 0700 "${BUILD_DIR}/var/lib/meshfs" "${BUILD_DIR}/var/lib/meshfs/s3" \
  "${BUILD_DIR}/var/lib/meshfs/s3/buckets" "${BUILD_DIR}/var/lib/meshfs/s3/multipart" "${BUILD_DIR}/var/lib/meshfs/s3/quotas"

install -m 0755 "${RUST_BIN}" "${BUILD_DIR}/usr/bin/meshfs-s3"

cat <<'EOF' > "${BUILD_DIR}/etc/meshfs/s3.json"
{
  "version": "2.3.0",
  "bind_addr": "127.0.0.1:9000",
  "cas_dir": "/var/lib/meshfs",
  "s3_dir": "/var/lib/meshfs/s3",
  "control_socket": "/var/lib/meshfs/s3.sock",
  "worm_compliance_enabled": true
}
EOF
chmod 0600 "${BUILD_DIR}/etc/meshfs/s3.json"

cat <<'EOF' > "${BUILD_DIR}/DEBIAN/conffiles"
/etc/meshfs/s3.json
EOF
chmod 0644 "${BUILD_DIR}/DEBIAN/conffiles"

cat <<'EOF' > "${BUILD_DIR}/usr/lib/systemd/system/meshfs-s3.service"
[Unit]
Description=PodMesh MeshFS S3 Gateway v2.3.0 (4 MiB SHA-256 CAS Object Storage)
After=network-online.target meshfs.service
Wants=network-online.target meshfs.service
Documentation=https://github.com/xavdp-pro/podmesh-meshfs-s3

[Service]
Type=simple
User=root
Group=root
UMask=0077
EnvironmentFile=-/etc/meshfs/s3.env
ExecStart=/usr/bin/meshfs-s3 daemon --bind 127.0.0.1:9000 --cas-dir /var/lib/meshfs --s3-dir /var/lib/meshfs/s3 --socket /var/lib/meshfs/s3.sock
Restart=on-failure
RestartSec=3
LimitNOFILE=1048576
NoNewPrivileges=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
EOF
chmod 0644 "${BUILD_DIR}/usr/lib/systemd/system/meshfs-s3.service"

INSTALLED_SIZE=$(du -sk "${BUILD_DIR}" | awk '{print $1}')

cat <<EOF > "${BUILD_DIR}/DEBIAN/control"
Package: ${PKG_NAME}
Version: ${PKG_VERSION}
Section: admin
Priority: optional
Architecture: ${PKG_ARCH}
Installed-Size: ${INSTALLED_SIZE}
Depends: libc6 (>= 2.38), podmesh-meshfs (>= 2.3.0)
Provides: meshfs-s3, podmesh-s3
Maintainer: Xavier de Poorter <xavier@xavdp.pro>
Homepage: https://github.com/xavdp-pro/podmesh-meshfs-s3
Description: Sovereign S3-Compatible Object Storage Gateway backed by MeshFS CAS (v2.4.1)
 Pure Rust S3 Object Storage Gateway and AI-First CLI sharing the MeshFS
 4 MiB FastCDC SHA-256 Content-Addressable Storage pool. Supports O(1)
 Multipart Upload sealing, HTTP 206 Range slicing, WORM Object Lock
 anti-ransomware compliance, and HMAC-SHA256 presigned URLs.
EOF
chmod 0644 "${BUILD_DIR}/DEBIAN/control"

cat <<'EOF' > "${BUILD_DIR}/DEBIAN/postinst"
#!/bin/sh
set -e

if [ "$1" = "configure" ]; then
    install -d -m 0700 -o root -g root /etc/meshfs
    install -d -m 0700 -o root -g root /var/lib/meshfs
    install -d -m 0700 -o root -g root /var/lib/meshfs/chunks
    install -d -m 0700 -o root -g root /var/lib/meshfs/s3
    install -d -m 0700 -o root -g root /var/lib/meshfs/s3/buckets
    install -d -m 0700 -o root -g root /var/lib/meshfs/s3/multipart
    install -d -m 0700 -o root -g root /var/lib/meshfs/s3/quotas

    ENV_FILE="/etc/meshfs/s3.env"
    if [ ! -f "$ENV_FILE" ] || ! grep -q "^MESHFS_S3_SECRET_KEY=" "$ENV_FILE" 2>/dev/null; then
        TMP_ENV="/etc/meshfs/.s3.env.tmp.$$"
        OLD_UMASK=$(umask)
        umask 0077
        AK_HEX=$(od -An -N9 -tx1 /dev/urandom | tr -d ' \n' | tr 'a-f' 'A-F')
        SK_HEX=$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')
        cat <<EOT > "$TMP_ENV"
# Auto-generated by podmesh-meshfs-s3 postinst (CSPRNG)
MESHFS_S3_ACCESS_KEY=PM${AK_HEX}
MESHFS_S3_SECRET_KEY=${SK_HEX}
MESHFS_S3_BIND=127.0.0.1:9000
EOT
        chmod 0600 "$TMP_ENV"
        chown root:root "$TMP_ENV"
        mv -f "$TMP_ENV" "$ENV_FILE"
        umask "$OLD_UMASK"
        echo "[MeshFS-S3] Generated CSPRNG S3 credentials in $ENV_FILE (mode 0600)."
    fi

    if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then
        systemctl daemon-reload >/dev/null 2>&1 || true
        systemctl enable meshfs-s3.service >/dev/null 2>&1 || true
        systemctl restart meshfs-s3.service >/dev/null 2>&1 || true
        echo "[MeshFS-S3] Service meshfs-s3.service (v2.4.1) enabled and started on 127.0.0.1:9000 + /var/lib/meshfs/s3.sock."
    fi
fi

exit 0
EOF
chmod 0755 "${BUILD_DIR}/DEBIAN/postinst"

cat <<'EOF' > "${BUILD_DIR}/DEBIAN/prerm"
#!/bin/sh
set -e

if [ "$1" = "remove" ] || [ "$1" = "deconfigure" ]; then
    if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then
        systemctl stop meshfs-s3.service >/dev/null 2>&1 || true
        systemctl disable meshfs-s3.service >/dev/null 2>&1 || true
    fi
    rm -f /var/lib/meshfs/s3.sock
fi

exit 0
EOF
chmod 0755 "${BUILD_DIR}/DEBIAN/prerm"

cat <<'EOF' > "${BUILD_DIR}/DEBIAN/postrm"
#!/bin/sh
set -e

if [ "$1" = "purge" ]; then
    rm -rf /etc/meshfs/s3.env /etc/meshfs/s3.json /var/lib/meshfs/s3.sock /var/lib/meshfs/s3
fi

if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then
    systemctl daemon-reload >/dev/null 2>&1 || true
fi

exit 0
EOF
chmod 0755 "${BUILD_DIR}/DEBIAN/postrm"

mkdir -p "${DIST_DIR}"
DEB_OUT="${DIST_DIR}/${PKG_NAME}_${PKG_VERSION}_${PKG_ARCH}.deb"
SOURCE_DATE_EPOCH="${SOURCE_DATE_EPOCH:-1761609600}" dpkg-deb --root-owner-group -Zxz --build "${BUILD_DIR}" "${DEB_OUT}"

ROOT_PERM=$(dpkg-deb -c "${DEB_OUT}" | awk '$6 == "./" {print $1}')
if [ "${ROOT_PERM}" != "drwxr-xr-x" ]; then
    echo "FATAL: Archive root ./ has permissions ${ROOT_PERM} instead of drwxr-xr-x (0755)!" >&2
    exit 1
fi

echo "[MeshFS-S3] Debian 13 package built & verified: ${DEB_OUT}"
sha256sum "${DEB_OUT}" | tee "${DIST_DIR}/SHA256SUMS"
